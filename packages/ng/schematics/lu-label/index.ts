import type { Rule, Tree } from '@angular-devkit/schematics';
import { currentSchematicContext, migrateFile, SchematicContextOpts } from '../lib';
import { LabelMigrationState, LabelReportEntry, migrateComponent } from './migration';

// Nx need to see "@angular-devkit/schematics" in order to run this migration correctly (see https://github.com/nrwl/nx/blob/d9fed4b832bf01d1b9a44ae9e486a5e5cd2d2253/packages/nx/src/command-line/migrate/migrate.ts#L1729-L1738)
// eslint-disable-next-line @typescript-eslint/no-require-imports
require('@angular-devkit/schematics');

export const REPORT_PATH = 'lu-label-migration-report.md';

/** Imports bringing the label CSS: `.label` has no Angular component, its styles only come from one of them. */
const labelCssImport = /@lucca-front\/scss\/src\/(components\/label|components|main-all)(\/index)?(\.scss)?['"]/;

interface LabelCss {
	/** True when `components` or `main-all` is imported: every component CSS is already there. */
	allComponents: boolean;
	/** Stylesheet and line importing the label CSS on its own, where the HTML fallback imports go. */
	labelImport?: { path: string; line: string };
}

export default (options?: SchematicContextOpts): Rule => {
	return async (tree, context) => {
		await currentSchematicContext.init(context, options);

		const labelCss = findLabelCss(tree);

		if (!labelCss) {
			context.logger.info('Label CSS not imported, nothing to migrate.');
			return;
		}

		const state: LabelMigrationState = { entries: [], fallbackComponents: new Set() };

		// Templates are reached through their component: the new components go into its `imports`.
		tree.visit((path, entry) => {
			if (path.includes('node_modules') || !entry) {
				return;
			}

			if (path.endsWith('.ts') && !path.endsWith('.d.ts')) {
				migrateFile(path, entry, tree, (content) => migrateComponent(path, content, tree, state));
			}
		});

		addFallbackImports(tree, labelCss, state, (message) => context.logger.warn(message));

		if (state.entries.length === 0) {
			context.logger.info('No .label found in the templates.');
			return;
		}

		const report = buildReport(state.entries);
		if (tree.exists(REPORT_PATH)) {
			tree.overwrite(REPORT_PATH, report);
		} else {
			tree.create(REPORT_PATH, report);
		}

		context.logger.info(buildSummary(state.entries));
	};
};

function findLabelCss(tree: Tree): LabelCss | null {
	let found: LabelCss | null = null;

	tree.visit((path, entry) => {
		if (path.includes('node_modules') || !entry || !/\.(s?css|sass)$|\/(angular|project)\.json$/.test(path)) {
			return;
		}

		entry.content
			.toString()
			.split('\n')
			.forEach((line) => {
				// A commented import brings no CSS.
				const match = /^\s*(\/\/|\/\*|\*)/.test(line) ? null : line.match(labelCssImport);
				if (!match) {
					return;
				}
				found ??= { allComponents: false };
				if (match[1] === 'components/label') {
					found.labelImport ??= { path, line };
				} else {
					found.allComponents = true;
				}
			});
	});

	return found;
}

function addFallbackImports(tree: Tree, labelCss: LabelCss, state: LabelMigrationState, warn: (message: string) => void): void {
	if (state.fallbackComponents.size === 0 || labelCss.allComponents || !labelCss.labelImport) {
		return;
	}

	const { path, line } = labelCss.labelImport;

	if (!/\.(s?css|sass)$/.test(path)) {
		warn(`The label CSS is imported from ${path}: import ${[...state.fallbackComponents].join(' and ')} there by hand for the HTML fallbacks.`);
		return;
	}

	const content = tree.readText(path);
	const imports = [...state.fallbackComponents]
		.sort()
		// The namespace (`as label`) and the configuration (`with (…)`) belong to the label import only.
		.map((component) =>
			line
				.replace(/components\/label(?=(\/index)?(\.scss)?['"])/, `components/${component}`)
				.replace(/(['"])\s+(as\s+[\w*-]+|with\s*\([^)]*\))[^;]*;/, '$1;'),
		)
		.filter((importLine) => !content.includes(importLine.trim()));

	if (imports.length > 0) {
		tree.overwrite(path, content.replace(line, [line, ...imports].join('\n')));
	}
}

function buildReport(entries: LabelReportEntry[]): string {
	const rows = [...entries]
		.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line)
		.map((entry) => `| ${entry.file}:${entry.line} | ${entry.target} | ${entry.confidence} | ${entry.reason} |`);

	return [
		'# Label migration report',
		'',
		'Generated by `ng g @lucca-front/ng:lu-label`. Review the `low` and `not converted` rows, then delete this file.',
		'',
		'| File:line | Target | Confidence | Reason |',
		'|---|---|---|---|',
		...rows,
		'',
	].join('\n');
}

function buildSummary(entries: LabelReportEntry[]): string {
	const count = (predicate: (entry: LabelReportEntry) => boolean) => entries.filter(predicate).length;
	const converted = entries.filter((entry) => entry.confidence !== 'not converted');
	const targets = [...new Set(converted.map((entry) => entry.target))].map((target) => `${target}: ${count((entry) => entry.target === target)}`);

	return [
		`Label migration: ${converted.length} converted (${targets.join(', ') || 'none'}), ${count((entry) => entry.confidence === 'low')} to review, ${count((entry) => entry.confidence === 'not converted')} not converted.`,
		`See ${REPORT_PATH}.`,
	].join('\n');
}
