import type { Rule } from '@angular-devkit/schematics';
import { currentSchematicContext, migrateFile, SchematicContextOpts } from '../lib';
import { hasTextSizeToken, migrateComponent, reportOccurrences, TextSizeMigrationState, TextSizeReportEntry } from './migration';

// Nx need to see "@angular-devkit/schematics" in order to run this migration correctly (see https://github.com/nrwl/nx/blob/d9fed4b832bf01d1b9a44ae9e486a5e5cd2d2253/packages/nx/src/command-line/migrate/migrate.ts#L1729-L1738)
// eslint-disable-next-line @typescript-eslint/no-require-imports
require('@angular-devkit/schematics');

export const REPORT_PATH = 'text-size-migration-report.md';

export default (options?: SchematicContextOpts): Rule => {
	return async (tree, context) => {
		await currentSchematicContext.init(context, options);

		const state: TextSizeMigrationState = { entries: [], templates: new Set() };

		// Components first: their templates are migrated with the element context.
		tree.visit((path, entry) => {
			if (path.includes('node_modules') || !entry) {
				return;
			}

			if (path.endsWith('.ts') && !path.endsWith('.d.ts')) {
				migrateFile(path, entry, tree, (content) => migrateComponent(path, content, tree, state));
			}
		});

		// Then what no component template reached: stylesheets and loose HTML files are only listed.
		tree.visit((path, entry) => {
			if (path.includes('node_modules') || !entry || state.templates.has(path)) {
				return;
			}

			const content = entry.content.toString();

			if (/\.(s?css|sass|less)$/.test(path) && hasTextSizeToken(content)) {
				reportOccurrences(path, content, state.entries, 'stylesheet');
			} else if (path.endsWith('.html') && hasTextSizeToken(content)) {
				reportOccurrences(path, content, state.entries, 'HTML file outside a component template');
			}
		});

		if (state.entries.length === 0) {
			// A report from a previous run would list rows that no longer exist.
			if (tree.exists(REPORT_PATH)) {
				tree.delete(REPORT_PATH);
			}
			context.logger.info('No deprecated text size utility found.');
			return;
		}

		const report = buildReport(state.entries);
		if (tree.exists(REPORT_PATH)) {
			tree.overwrite(REPORT_PATH, report);
		} else {
			tree.create(REPORT_PATH, report);
		}

		context.logger.info(`${buildSummary(state.entries)}\nSee ${REPORT_PATH}.`);
	};
};

function buildSummary(entries: TextSizeReportEntry[]): string {
	const converted = entries.filter((entry) => entry.confidence === 'high');
	const notConverted = entries.length - converted.length;

	// One count per replacement, `textS → bodyS`, the most frequent first: `u-textS` and `pr-u-textS` are counted together.
	const perReplacement = new Map<string, number>();
	converted.forEach((entry) => {
		const replacement = `${entry.from.replace(/^(pr-)?u-/, '')} → ${entry.to?.replace(/^pr-u-/, '')}`;
		perReplacement.set(replacement, (perReplacement.get(replacement) ?? 0) + 1);
	});
	const details = [...perReplacement].sort(([, a], [, b]) => b - a).map(([replacement, count]) => `${replacement}: ${count}`);

	return `Text size migration: ${converted.length} converted${details.length ? ` (${details.join(', ')})` : ''}, ${notConverted} not converted.`;
}

function buildReport(entries: TextSizeReportEntry[]): string {
	// `high` rows are only counted: there can be hundreds of them, none needing a review.
	const rows = entries
		.filter((entry) => entry.confidence !== 'high')
		.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line)
		.map((entry) => `| ${entry.file}:${entry.line} | ${entry.from} → ${entry.to ?? '—'} | ${entry.confidence} | ${entry.reason} |`);

	return [
		'# Text size migration report',
		'',
		'Generated by `ng g @lucca-front/ng:text-size`. Handle the `not converted` rows by hand if needed, then delete this file.',
		'',
		'The replacements use the `font` shorthand without `!important`: a project style setting a font size on the same element now wins over them. Check the screens where that is the case.',
		'',
		buildSummary(entries),
		'',
		'| File:line | From → To | Confidence | Reason |',
		'|---|---|---|---|',
		...rows,
		'',
	].join('\n');
}
