/**
 * Generates docs/schematics.md, the "Released" table of the Prisme "Cycle de vie des composants" page
 * (zeroheight syncs it from master), from the `documentation` field of each schematic in collection.json:
 *
 *   "documentation": { "description": "<French description, markdown>" }
 *   "documentation": { "description": "…", "since": "<X.Y or X.Y.Z>" }   → forces the displayed version
 *   "documentation": false   → deliberately left out of the table
 *
 * Without `since`, the version is the first release tag containing the schematic, so that a schematic
 * shipped in a patch from master gets its patch version; until it is tagged, it shows "Prochaine version".
 *
 * Usage: node scripts/schematics-doc.mjs [--check]
 *   --check  fails if docs/schematics.md is not up to date or a schematic has no documentation, without writing it
 *
 * Without --check (pre-commit hook), a schematic without documentation only raises a warning: /release completes it.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const COLLECTION = join(ROOT, 'packages/ng/schematics/collection.json');
const OUTPUT = join(ROOT, 'docs/schematics.md');
const UNRELEASED = 'Prochaine version';

/** Not a migration: installs Lucca Front. */
const NOT_A_MIGRATION = new Set(['ng-add']);

const { schematics } = JSON.parse(readFileSync(COLLECTION, 'utf8'));
const rows = [];
const missing = [];

for (const [name, schematic] of Object.entries(schematics)) {
	if (NOT_A_MIGRATION.has(name) || schematic.documentation === false) {
		continue;
	}

	const { description, since } = schematic.documentation ?? {};

	if (!description || (since !== undefined && !/^\d+\.\d+(\.\d+)?$/.test(since))) {
		missing.push(name);
		continue;
	}

	rows.push({ name, description, since: since ?? releasedIn(name) });
}

// Completed at release time (/release): a schematic PR is not blocked, its row only waits for its description.
if (missing.length > 0) {
	console.warn(
		`Missing or invalid "documentation" in packages/ng/schematics/collection.json for: ${missing.join(', ')}, left out of docs/schematics.md.\n` +
			'Add { "description": "<French description>" }, or `"documentation": false` to leave it out on purpose.',
	);
}

function compareVersions(a, b) {
	// Not tagged yet: newer than any release.
	if (a === UNRELEASED || b === UNRELEASED) {
		return (a === UNRELEASED) - (b === UNRELEASED);
	}
	const [pa, pb] = [a, b].map((version) => version.split('.').map(Number));
	for (let i = 0; i < 3; i++) {
		if ((pa[i] ?? 0) !== (pb[i] ?? 0)) {
			return (pa[i] ?? 0) - (pb[i] ?? 0);
		}
	}
	return 0;
}

/** First release tag containing the commit that added the schematic to the collection: `22.2`, `22.0.3`, or UNRELEASED. */
function releasedIn(name) {
	const git = (...args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();
	const [added] = git('log', '--reverse', '--format=%H', `-S"${name}": {`, '--', 'packages/ng/schematics/collection.json').split('\n');

	// Not committed yet.
	if (!added) {
		return UNRELEASED;
	}

	const [first] = git('tag', '--contains', added, '--list', 'v*')
		.split('\n')
		.filter((tag) => /^v\d+\.\d+\.\d+$/.test(tag))
		.map((tag) => tag.slice(1))
		.sort(compareVersions);

	return first ? first.replace(/\.0$/, '') : UNRELEASED;
}

// Newest first, then by name for a stable order.
rows.sort((a, b) => compareVersions(b.since, a.since) || a.name.localeCompare(b.name));

const content = [
	'<!-- Generated by `npm run schematics:doc` from the `documentation` field of packages/ng/schematics/collection.json: do not edit by hand. -->',
	'',
	'| Description | Versions | Commande |',
	'| --- | --- | --- |',
	...rows.map(({ name, description, since }) => `| ${description} | ${since === UNRELEASED ? since : `${since}+`} | \`ng g @lucca-front/ng:${name}\` |`),
	'',
].join('\n');

if (process.argv.includes('--check')) {
	let current = '';
	try {
		current = readFileSync(OUTPUT, 'utf8');
	} catch {
		// missing file: out of date
	}
	if (current !== content) {
		console.error('docs/schematics.md is out of date: run `npm run schematics:doc`.');
		process.exit(1);
	}
	if (missing.length > 0) {
		process.exit(1);
	}
	console.log('docs/schematics.md is up to date.');
} else {
	writeFileSync(OUTPUT, content);
	console.log(`docs/schematics.md — ${rows.length} schematics.`);
}
